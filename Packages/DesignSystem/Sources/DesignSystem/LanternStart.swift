import CoreGraphics
import SwiftUI

/// The start: the lantern lights up. The lantern from the app icon stands dark
/// on paper, glimmers up with a short flicker, its glow grows, it lifts and
/// releases the start page - whose cover glow picks up the light
/// (origin in motion: nothing appears out of nothing).
///
/// **Short, not the loop from the mockup**: about 1.6 s from the first frame to the start page,
/// without waiting for anything - the shell loads underneath already. Taps pass through
/// (`allowsHitTesting(false)`), whoever is in a hurry does not wait.
///
/// The two layers (`laterne-aus`, `laterne-an`) are generated by a script;
/// the glow is painted by the view itself so it can grow. Whether the view appears at all
/// ("Reduce Motion", mocks, UI tests) is decided by the app.
public struct LanternStart: View {

    private let done: @MainActor () -> Void

    @Environment(\.theme) private var theme

    /// Opacity of the lit layer over the dark one.
    @State private var glut = 0.0
    @State private var halo = 0.4
    @State private var haloOpacity = 0.0
    @State private var lifted = false
    @State private var route = false

    /// - Parameter done: called when the start page is free.
    public init(done: @escaping @MainActor () -> Void) {
        self.done = done
    }

    /// Amber from the glow of the app icon (`#FFC27A`).
    private static let light = Color(red: 1, green: 0.761, blue: 0.478)

    public var body: some View {
        ZStack {
            theme.paper.color.ignoresSafeArea()
            RadialGradient(
                colors: [LanternStart.light.opacity(0.55), LanternStart.light.opacity(0)],
                center: .center, startRadius: 0, endRadius: 150
            )
            .frame(width: 300, height: 300)
            .scaleEffect(halo)
            .opacity(haloOpacity)
            ZStack {
                layer(LanternStart.from)
                layer(LanternStart.to).opacity(glut)
            }
            .frame(width: 160, height: 160)
            .scaleEffect(lifted ? 0.82 : 1)
            .offset(y: lifted ? -60 : 0)
            .opacity(lifted ? 0 : 1)
        }
        .opacity(route ? 0 : 1)
        .allowsHitTesting(false)
        .accessibilityHidden(true)
        .task { await flow() }
    }

    @ViewBuilder
    private func layer(_ image: CGImage?) -> some View {
        if let image {
            Image(decorative: image, scale: 1)
                .resizable()
                .scaledToFit()
        }
    }

    /// The timings follow the mockup (6 s loop), compressed into the single pass:
    /// stand dark, flicker, glow up, lift and widen the glow, fade out.
    private func flow() async {
        await pause(0.15)
        withAnimation(.easeOut(duration: 0.12)) { glut = 0.55 }
        await pause(0.12)
        withAnimation(.easeIn(duration: 0.1)) { glut = 0.35 }
        await pause(0.1)
        withAnimation(.easeOut(duration: 0.38)) {
            glut = 1
            halo = 1
            haloOpacity = 1
        }
        await pause(0.45)
        withAnimation(.easeInOut(duration: 0.55)) {
            lifted = true
            halo = 1.9
            haloOpacity = 0.9
        }
        await pause(0.4)
        withAnimation(.easeOut(duration: 0.3)) { route = true }
        await pause(0.3)
        done()
    }

    private func pause(_ seconds: Double) async {
        try? await Task.sleep(for: .seconds(seconds))
    }

    // Not main-actor bound, so ``prepare()`` can decode them in the background; a `CGImage`
    // is immutable.
    nonisolated private static let to = Brand.load("laterne-an")
    nonisolated private static let from = Brand.load("laterne-aus")

    /// Decodes both layers off the main thread — the app calls it at launch, before the first
    /// frame needs them.
    public static func prepare() {
        Task.detached(priority: .userInitiated) {
            _ = LanternStart.to
            _ = LanternStart.from
        }
    }
}
